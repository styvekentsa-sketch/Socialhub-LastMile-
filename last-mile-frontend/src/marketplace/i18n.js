const readKey = (source, key) => key.split('.').reduce((value, part) => value?.[part], source)

export function useMarketplaceText() {
  const { language, setLanguage } = useLanguage()

  const t = useCallback((key, variables = {}) => {
    const value = readKey(TEXT[language], key) ?? readKey(TEXT.fr, key)
    if (Array.isArray(value)) return value
    return typeof value === 'string'
      ? value.replace(/\{\{(\w+)\}\}/g, (_, name) => String(variables[name] ?? ''))
      : key
  }, [language])

  // Prix en francs CFA (XAF) : « 38 000 FCFA » en francais
  const formatPrice = useCallback((value) => new Intl.NumberFormat(
    language === 'fr' ? 'fr-FR' : 'en-US',
    { style: 'currency', currency: 'XAF', maximumFractionDigits: 0 },
  ).format(Number(value) || 0), [language])

  const formatNumber = useCallback((value) => new Intl.NumberFormat(
    language === 'fr' ? 'fr-FR' : 'en-US',
  ).format(Number(value) || 0), [language])

  return useMemo(() => ({ t, language, setLanguage, formatPrice, formatNumber }), [t, language, setLanguage, formatPrice, formatNumber])
}
