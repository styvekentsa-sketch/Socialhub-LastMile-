const readKey = (source, key) => key.split('.').reduce((value, part) => value?.[part], source)

export function useMarketplaceText() {
  const { language, setLanguage } = useLanguage()
  // Devise d'affichage choisie dans l'en-tete (FCFA hors du portail ou par defaut)
  const currency = useCurrency()?.currency || DEFAULT_CURRENCY

  const t = useCallback((key, variables = {}) => {
    const value = readKey(TEXT[language], key) ?? readKey(TEXT.fr, key)
    if (Array.isArray(value)) return value
    return typeof value === 'string'
      ? value.replace(/\{\{(\w+)\}\}/g, (_, name) => String(variables[name] ?? ''))
      : key
  }, [language])

  // Prix stockes en francs CFA (XAF), affiches dans la devise choisie : « 38 000 FCFA », « 57,93 € », « $63.33 »
  const formatPrice = useCallback((value) => {
    const { decimals } = CURRENCIES[currency]
    return new Intl.NumberFormat(language === 'fr' ? 'fr-FR' : 'en-US', {
      style: 'currency', currency, minimumFractionDigits: decimals, maximumFractionDigits: decimals,
    }).format(convertFromXaf(value, currency))
  }, [language, currency])

  const formatNumber = useCallback((value) => new Intl.NumberFormat(
    language === 'fr' ? 'fr-FR' : 'en-US',
  ).format(Number(value) || 0), [language])

  return useMemo(() => ({ t, language, setLanguage, currency, formatPrice, formatNumber }), [t, language, setLanguage, currency, formatPrice, formatNumber])
}
